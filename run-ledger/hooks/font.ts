// Each glyph as GLYPH_H rows of GLYPH_W bits, most significant bit leftmost.
const BITS = new Map<string, Uint8Array>()
for (const [ch, art] of Object.entries(G)) {
  const rows = new Uint8Array(GLYPH_H)
  art.split('|').forEach((row, r) => {
    let bits = 0
    for (let c = 0; c < GLYPH_W; c++) if (row[c] === '#') bits |= 1 << (GLYPH_W - 1 - c)
    if (r < GLYPH_H) rows[r] = bits
  })
  BITS.set(ch, rows)
}

/** Letters with accents drawn as their base letter; anything else unknown as '?'. */
function plain(ch: string): string {
  if (BITS.has(ch)) return ch
  const base = ch.normalize('NFD').replace(/[̀-ͯ]/g, '')
  return BITS.has(base) ? base : '?'
}

/** The rows of `ch`. */
export function glyph(ch: string): Uint8Array {
  return BITS.get(plain(ch)) ?? (BITS.get('?') as Uint8Array)
}

/** Pixel width of `text` at `scale` (pixels per font pixel). */
export const textWidth = (text: string, scale: number): number => Math.max(0, [...text].length * ADVANCE * scale - scale)

const SMOOTH = new Map<string, Uint8Array>()

/**
 * The glyph doubled with Scale2x (EPX): `2 * GLYPH_W` by `2 * GLYPH_H`, one byte a pixel,
 * steps along a diagonal filled in so strokes read as lines rather than stairs.
 */
export function smoothGlyph(ch: string): Uint8Array {
  const key = plain(ch)
  const known = SMOOTH.get(key)
  if (known) return known
  const rows = glyph(key)
  const at = (r: number, c: number): number => (r < 0 || r >= GLYPH_H || c < 0 || c >= GLYPH_W ? 0 : ((rows[r] ?? 0) >> (GLYPH_W - 1 - c)) & 1)
  const w = GLYPH_W * 2
  const out = new Uint8Array(w * GLYPH_H * 2)
  for (let r = 0; r < GLYPH_H; r++) {
    for (let c = 0; c < GLYPH_W; c++) {
      const p = at(r, c)
      const a = at(r - 1, c)
      const b = at(r, c + 1)
      const cc = at(r, c - 1)
      const d = at(r + 1, c)
      out[2 * r * w + 2 * c] = cc === a && cc !== d && a !== b ? a : p
      out[2 * r * w + 2 * c + 1] = a === b && a !== cc && b !== d ? b : p
      out[(2 * r + 1) * w + 2 * c] = d === cc && d !== b && cc !== a ? cc : p
      out[(2 * r + 1) * w + 2 * c + 1] = b === d && b !== a && d !== cc ? d : p
    }
  }
  SMOOTH.set(key, out)
  return out
}
